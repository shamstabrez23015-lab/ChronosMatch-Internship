"""ChronosMatch Order Adapter: Bridge between Shared IPC Ring Buffer and Cython Matching Engine.

Provides an integration adapter that:
1. Drains binary-unpacked order tuples from MmapRingBuffer (or ZeroCopyConsumer).
2. Maps binary protocol parameters (order_id, timestamp_ns, price, quantity, symbol_id, side, order_type)
   into the Cython MatchingEngine's supported interfaces (match_order / submit_order).
3. Supports single-engine operation or multi-symbol routing (symbol_id -> MatchingEngine).
4. Truthfully handles order types (LIMIT supported; CANCEL / MARKET tracked if not natively supported).
5. Collects executed TradeResult records and adapter throughput / matching statistics.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Tuple, Union

from chronos.matching_engine import MatchingEngine, TradeResult, price_to_cents
from chronos.protocol import Order, OrderType, Side, SYMBOLS, SYMBOL_ID_TO_TICKER
from chronos.ring_buffer import MmapRingBuffer
from chronos.consumer import ZeroCopyConsumer


@dataclass
class AdapterStats:
    """Operational statistics for OrderAdapter."""

    total_orders_read: int = 0
    total_orders_dispatched: int = 0
    total_trades_generated: int = 0
    total_volume_matched: int = 0
    non_crossing_orders: int = 0
    unhandled_order_types: int = 0
    unrouted_symbols: int = 0

    def reset(self) -> None:
        """Reset all metrics to zero."""
        self.total_orders_read = 0
        self.total_orders_dispatched = 0
        self.total_trades_generated = 0
        self.total_volume_matched = 0
        self.non_crossing_orders = 0
        self.unhandled_order_types = 0
        self.unrouted_symbols = 0


class OrderAdapter:
    """Adapts raw IPC ring buffer orders into Cython MatchingEngine calls.

    Bridges the gap between the 7-parameter binary protocol / ring buffer layout
    (order_id, timestamp_ns, price, quantity, symbol_id, side, order_type)
    and the 5-parameter MatchingEngine C interface (order_id, side, price, quantity, timestamp_ns).
    """

    def __init__(
        self,
        ring_buffer: Optional[MmapRingBuffer] = None,
        engine: Optional[MatchingEngine] = None,
        symbol_engines: Optional[Dict[int, MatchingEngine]] = None,
        default_symbol_id: Optional[int] = None,
        dispatch_mode: str = "match",
    ):
        """Initialize OrderAdapter.

        Args:
            ring_buffer: Backing MmapRingBuffer to drain from (optional).
            engine: Primary/default MatchingEngine instance.
            symbol_engines: Optional dictionary mapping symbol_id (uint16) to MatchingEngine.
            default_symbol_id: Default symbol ID when using a single engine.
            dispatch_mode: 'match' to invoke engine.match_order (active matching);
                           'submit' to invoke engine.submit_order (passive storage).
        """
        self.ring_buffer = ring_buffer
        self.default_engine = engine
        self.symbol_engines: Dict[int, MatchingEngine] = symbol_engines or {}
        self.default_symbol_id = default_symbol_id
        if engine is not None and default_symbol_id is not None:
            self.symbol_engines[default_symbol_id] = engine

        if dispatch_mode not in ("match", "submit"):
            raise ValueError(f"Invalid dispatch_mode '{dispatch_mode}': must be 'match' or 'submit'")
        self.dispatch_mode = dispatch_mode

        self.stats = AdapterStats()
        self.trades: List[TradeResult] = []
        self.unhandled_orders: List[Tuple[Any, str]] = []
        self.unrouted_orders: List[Any] = []

    def resolve_engine(self, symbol_id: int) -> Optional[MatchingEngine]:
        """Resolve the target MatchingEngine for a given symbol_id."""
        if symbol_id in self.symbol_engines:
            return self.symbol_engines[symbol_id]
        if self.default_engine is not None:
            return self.default_engine
        return None

    def dispatch_raw_order(
        self, raw_order: Union[Tuple[int, int, float, int, int, int, int], Order]
    ) -> List[TradeResult]:
        """Dispatch a single raw order tuple or Order instance into the matching engine.

        Parameters:
            raw_order: 7-tuple (order_id, timestamp_ns, price, quantity, symbol_id, side, order_type)
                       or chronos.protocol.Order NamedTuple.

        Returns:
            List of TradeResult objects generated by this order.
        """
        if isinstance(raw_order, Order):
            order_id = int(raw_order.order_id)
            timestamp_ns = int(raw_order.timestamp_ns)
            price = float(raw_order.price)
            quantity = int(raw_order.quantity)
            symbol_id = int(raw_order.symbol_id)
            side = int(raw_order.side)
            order_type = int(raw_order.order_type)
        else:
            order_id = int(raw_order[0])
            timestamp_ns = int(raw_order[1])
            price = float(raw_order[2])
            quantity = int(raw_order[3])
            symbol_id = int(raw_order[4])
            side = int(raw_order[5])
            order_type = int(raw_order[6])

        target_engine = self.resolve_engine(symbol_id)
        if target_engine is None:
            self.stats.unrouted_symbols += 1
            self.unrouted_orders.append(raw_order)
            return []

        # Check order type compatibility
        if order_type == int(OrderType.LIMIT):
            if self.dispatch_mode == "match":
                trades = target_engine.match_order(
                    order_id=order_id,
                    side=side,
                    price=price,
                    quantity=quantity,
                    timestamp_ns=timestamp_ns,
                )
                self.trades.extend(trades)
                self.stats.total_orders_dispatched += 1
                self.stats.total_trades_generated += len(trades)
                self.stats.total_volume_matched += sum(t.executed_quantity for t in trades)
                if len(trades) == 0:
                    self.stats.non_crossing_orders += 1
                return trades
            else:
                target_engine.submit_order(
                    order_id=order_id,
                    side=side,
                    price=price,
                    quantity=quantity,
                    timestamp_ns=timestamp_ns,
                )
                self.stats.total_orders_dispatched += 1
                self.stats.non_crossing_orders += 1
                return []
        else:
            # Non-LIMIT order types (e.g. CANCEL, MARKET)
            # The current Cython matching engine does not natively support cancel or market orders yet.
            # Document and record truthfully without silently failing or crashing.
            self.stats.unhandled_order_types += 1
            self.unhandled_orders.append((raw_order, f"Unsupported order_type: {order_type}"))
            return []

    def process_next(
        self,
    ) -> Tuple[Optional[Tuple[int, int, float, int, int, int, int]], List[TradeResult]]:
        """Read a single raw order from the ring buffer and dispatch it.

        Returns:
            Tuple of (raw_order, list_of_trades). If buffer is empty, returns (None, []).
        """
        if self.ring_buffer is None:
            raise ValueError("Cannot process_next: no ring_buffer provided.")
        raw = self.ring_buffer.read_raw()
        if raw is None:
            return (None, [])
        self.stats.total_orders_read += 1
        trades = self.dispatch_raw_order(raw)
        return (raw, trades)

    def process_available(self, max_orders: Optional[int] = None) -> List[TradeResult]:
        """Drain and dispatch available orders from the ring buffer.

        Args:
            max_orders: Maximum number of orders to drain (defaults to all available).

        Returns:
            List of all TradeResult records generated from matching this batch.
        """
        if self.ring_buffer is None:
            raise ValueError("Cannot process_available: no ring_buffer provided.")
        avail = self.ring_buffer.available_to_read()
        if avail <= 0:
            return []
        count = avail if max_orders is None else min(avail, max_orders)
        batch = self.ring_buffer.read_batch_raw(max_items=count)
        self.stats.total_orders_read += len(batch)
        all_trades: List[TradeResult] = []
        for raw in batch:
            trades = self.dispatch_raw_order(raw)
            all_trades.extend(trades)
        return all_trades

    def drain_all(self) -> List[TradeResult]:
        """Drain all currently available orders in the ring buffer."""
        return self.process_available()

    def run_consumer(
        self,
        consumer: Optional[ZeroCopyConsumer] = None,
        total_orders: Optional[int] = None,
        duration_seconds: Optional[float] = None,
        print_progress: bool = False,
        exit_when_empty: bool = False,
    ) -> AdapterStats:
        """Run with a ZeroCopyConsumer to drain orders and dispatch to the matching engine.

        Bounded execution: stops after total_orders, duration_seconds, or when empty if exit_when_empty=True.
        """
        if consumer is None:
            if self.ring_buffer is None:
                raise ValueError("No ring_buffer or consumer provided.")
            consumer = ZeroCopyConsumer(
                self.ring_buffer,
                batch_size=1000,
                order_handler=self.dispatch_raw_order,
            )
        else:
            consumer.order_handler = self.dispatch_raw_order

        c_stats = consumer.run(
            total_orders=total_orders,
            duration_seconds=duration_seconds,
            print_progress=print_progress,
            exit_when_empty=exit_when_empty,
        )
        if c_stats is not None:
            self.stats.total_orders_read += c_stats.total_orders_read
        return self.stats

    def clear(self) -> None:
        """Reset adapter statistics and trade history."""
        self.stats.reset()
        self.trades.clear()
        self.unhandled_orders.clear()
        self.unrouted_orders.clear()

    def __enter__(self) -> OrderAdapter:
        return self

    def __exit__(self, exc_type, exc_val, exc_tb) -> None:
        self.clear()
